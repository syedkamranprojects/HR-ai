package dev.hrai.jobposting.agent;

import dev.hrai.jobposting.model.JobPosting;
import dev.hrai.jobposting.model.JobPostingDraft;
import dev.langchain4j.data.message.AiMessage;
import dev.langchain4j.data.message.UserMessage;
import dev.langchain4j.memory.ChatMemory;
import dev.langchain4j.memory.chat.MessageWindowChatMemory;
import dev.langchain4j.model.chat.ChatModel;
import dev.langchain4j.model.openai.OpenAiChatModel;
import dev.langchain4j.service.AiServices;
import dev.langchain4j.service.SystemMessage;

import java.util.List;

/**
 * Drafts a structured {@link JobPosting} from HR's free-text description of
 * a role, and refines it over follow-up turns ("make it stricter", "drop
 * the Docker requirement") the same way the onboarding agent handles
 * conversation history: the caller resends the full history each turn,
 * rebuilt into a ChatMemory here rather than kept server-side. This is a
 * draft only -- HR reviews and edits it before posting anywhere; nothing
 * here publishes on its own.
 */
public final class JobPostingDrafter {

    private static final String SYSTEM_PROMPT = """
            You turn a recruiter's free-text description of a role into a
            structured job posting draft. Separate hard requirements (a
            candidate must meet these to be considered at all) from preferred
            criteria (nice to have; a strong candidate may lack some of
            these) -- do not put the same requirement in both lists. If the
            prompt doesn't state something (employment type, location,
            education), make a reasonable best guess based on the role
            rather than leaving it empty, except educationRequirements: leave
            that an empty list if the prompt gives no signal either way.
            Write the summary in plain, professional language suitable for a
            public job listing, not a restatement of these instructions.

            The recruiter may send follow-up messages asking you to refine a
            posting you already drafted (e.g. "make it stricter", "drop the
            Docker requirement", "make it remote"). Each time, apply only the
            requested change on top of everything drafted so far, and always
            respond with the complete, updated posting -- every field, not
            just the parts that changed.
            """;

    private final ChatModel model;

    public JobPostingDrafter(String baseUrl, String apiKey, String modelName) {
        this.model = OpenAiChatModel.builder()
                .baseUrl(baseUrl)
                .apiKey(apiKey)
                .modelName(modelName)
                .build();
    }

    /**
     * @param history          the conversation so far: the initial role
     *                         description, then alternating draft/refinement
     *                         turns. Assistant turns carry the previous
     *                         JobPostingDraft serialized to text (see
     *                         {@link Turn}) so the model has its own prior
     *                         output to refine against.
     * @param applicationEmail where applicants should send their resume, as
     *                         typed by HR -- never generated by the model,
     *                         so it's never a guess. May be null/blank if HR
     *                         hasn't decided yet.
     */
    public JobPosting draft(List<Turn> history, String applicationEmail) {
        if (history.isEmpty()) {
            throw new IllegalArgumentException("history must contain at least one message");
        }

        ChatMemory memory = MessageWindowChatMemory.withMaxMessages(20);
        for (Turn turn : history.subList(0, history.size() - 1)) {
            memory.add(turn.isUser() ? UserMessage.from(turn.content()) : AiMessage.from(turn.content()));
        }
        String latestUserMessage = history.get(history.size() - 1).content();

        Drafter drafter = AiServices.builder(Drafter.class)
                .chatModel(model)
                .chatMemory(memory)
                .build();

        JobPostingDraft content = drafter.draft(latestUserMessage);
        return JobPosting.from(content, applicationEmail);
    }

    private interface Drafter {
        @SystemMessage(SYSTEM_PROMPT)
        JobPostingDraft draft(String message);
    }

    public record Turn(String role, String content) {
        public boolean isUser() {
            return "user".equals(role);
        }
    }
}
